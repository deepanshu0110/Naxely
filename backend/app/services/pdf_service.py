class _KPIRow(Flowable):
    """Ledger line-item for a single KPI: serif index, metric name, mono value,
    colored trend — hairline rules above and below the row."""

    def __init__(self, kpi, index, content_width, brand_color_hex):
        Flowable.__init__(self)
        self.kpi = kpi
        self.index = index
        self.brand_color_hex = brand_color_hex
        self._width = content_width
        self.height = 48

    def wrap(self, availWidth, availHeight):
        return (self._width, self.height)

    def draw(self):
        c = self.canv
        w = self._width
        h = self.height
        c.saveState()

        # hairlines above and below the ledger row
        c.setStrokeColor(HexColor(RULE))
        c.setLineWidth(0.4)
        c.line(0, 0, w, 0)
        c.line(0, h, w, h)

        # index — serif, muted
        c.setFillColor(HexColor(MUTED))
        c.setFont('Fraunces-Medium', 13)
        c.drawString(0, h - 30, str(self.index).zfill(2))

        # name — bold sans
        c.setFillColor(HexColor(INK))
        c.setFont('IBMPlexSans-Bold', 10)
        c.drawString(30, h - 18, str(self.kpi.get('name', '')))

        # value — mono bold, right of centre
        value = str(self.kpi.get('value', ''))
        c.setFillColor(HexColor(INK))
        c.setFont('IBMPlexMono-Bold', 14)
        c.drawRightString(w - 88, (h - 14) / 2 - 2, value)

        # trend — colored, far right. Colorblind-safe: arrow shape + sign +
        # color all carry direction, and up/down use the semantic ledger
        # mint/rust pair consistently with the AI insight cards.
        trend_pct = self.kpi.get('trend_pct', 0) or 0
        trend_color = DELTA_UP if trend_pct >= 0 else RUST
        sign = '+' if trend_pct >= 0 else '-'
        arrow = '\u2191' if trend_pct >= 0 else '\u2193'
        c.setFillColor(HexColor(trend_color))
        c.setFont('IBMPlexSans-Bold', 9)
        c.drawRightString(w, (h - 9) / 2 - 2,
                          f"{arrow} {sign} {abs(trend_pct):.1f}%")

        # qualifier under the trend — labels which calculation produced the
        # % (monthly-aggregate trend vs raw first-to-last), so the card never
        # silently contradicts a chart caption that uses the other measure
        qualifier = _trend_qualifier(self.kpi.get('trend_label', ''))
        if qualifier:
            c.setFillColor(HexColor(MUTED))
            c.setFont('IBMPlexSans-Bold', 6.5)
            c.drawRightString(w, 3, qualifier)

        c.restoreState()


def _wrap_text_lines(text: str, font_name: str, font_size: float, max_width: float) -> list[str]:
    """Greedy word wrap of `text` to `max_width` at the given font. Returns a
    list of lines, each fitting the box; an unbreakable word wider than the box
    is emitted alone rather than dropped."""
    lines, cur = [], ''
    for word in text.split(' '):
        trial = f'{cur} {word}'.strip()
        if cur and pdfmetrics.stringWidth(trial, font_name, font_size) > max_width:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines


def _fit_text_lines(text: str, font_name: str, font_size: float, max_width: float, max_lines: int) -> list[str]:
    """Wrap `text` to at most `max_lines` lines that fit `max_width`. When the
    text is longer, the final line is truncated at a word boundary with '…'
    rather than cutting mid-word."""
    lines = _wrap_text_lines(text, font_name, font_size, max_width)
    if len(lines) <= max_lines:
        return lines
    head = lines[:max_lines - 1]
    words = ' '.join(lines[max_lines - 1:]).split(' ')
    for n in range(len(words), 0, -1):
        candidate = ' '.join(words[:n]) + '\u2026'
        if pdfmetrics.stringWidth(candidate, font_name, font_size) <= max_width:
            return head + [candidate]
    return head + ['\u2026']


def _trend_qualifier(label: str) -> str:
    """Human-readable qualifier for a KPI trend %. Maps the machine
    `trend_label` ('recent' = monthly-aggregate trend, 'change' = raw
    first-to-last) to the phrase printed under the Key Metrics %."""
    return {
        'recent': 'monthly trend',
        'change': 'first-to-last',
    }.get(label, label)


def _truncate_words(text: str, limit: int) -> str:
    """Truncate `text` to at most `limit` characters at a word boundary,
    appending '…' — the char-based analogue of `_fit_text_lines` used where a
    fixed budget (table cells) applies. A single unbreakable word wider than
    the budget is cut at the limit rather than dropped."""
    if len(text) <= limit:
        return text
    words = text.split(' ')
    for n in range(len(words), 0, -1):
        candidate = ' '.join(words[:n])
        if len(candidate) <= limit - 1:
            return candidate + '\u2026'
    return text[:limit - 1] + '\u2026'


class _InsightCard(Flowable):
    """Ledger insight row: serif index, KPI name, severity tag, mono number,
    reason, and an arrowed action — hairline rule below the row. Long
    reason/action text wraps to a second line instead of being clipped
    mid-word; anything still over budget truncates at a word boundary."""

    CARD_H = 84
    LINE_H = 10
    PAD_LEFT = 30
    PAD_TOP = 12
    PAD_RIGHT = 8
    TAG_W = 44
    TAG_H = 13
    TEXT_FONT = 'IBMPlexSans'
    TEXT_SIZE = 8
    MAX_LINES = 2

    _MINT = HexColor(DELTA_UP)
    _RED = HexColor(RUST)
    _AMBER = HexColor('#B45309')
    _INK = HexColor(INK)
    _GRAY = HexColor(MUTED)
    _WHITE = HexColor('#FFFFFF')

    _PRIORITY_COLORS = {
        'high': _RED,
        'medium': _AMBER,
        'low': _MINT,
    }

    def __init__(self, insight, index=1, width=None):
        Flowable.__init__(self)
        self.insight = insight
        self.index = index
        self._width = width or (PAGE_WIDTH - 2 * MARGIN)
        self._reason_lines = []
        self._action_lines = []
        self._layout_text()

    def _layout_text(self):
        ins = self.insight
        reason = str(ins.get('reason', '') or '')
        action = str(ins.get('action', '') or '')
        avail_w = self._width - self.PAD_LEFT - self.PAD_RIGHT
        self._reason_lines = _fit_text_lines(
            reason, self.TEXT_FONT, self.TEXT_SIZE, avail_w, self.MAX_LINES)
        self._action_lines = _fit_text_lines(
            '\u2192 ' + action, self.TEXT_FONT, self.TEXT_SIZE, avail_w, self.MAX_LINES)

    def wrap(self, availWidth, availHeight):
        extra = (len(self._reason_lines) - 1) + (len(self._action_lines) - 1)
        return (self._width, self.CARD_H + extra * self.LINE_H)

    def draw(self):
        ins = self.insight
        kpi = str(ins.get('kpi', '') or '')
        number = str(ins.get('number', '') or '')
        priority = str(ins.get('priority', 'medium')).lower()

        priority_color = self._PRIORITY_COLORS.get(priority, self._AMBER)
        w = self._width
        c = self.canv
        h = self.height
        c.saveState()

        # hairline below the ledger row
        c.setStrokeColor(HexColor(RULE))
        c.setLineWidth(0.4)
        c.line(0, 0, w, 0)

        # index — serif, muted
        c.setFillColor(self._GRAY)
        c.setFont('Fraunces-Medium', 14)
        c.drawString(0, h - 26, str(self.index).zfill(2))

        text_x = self.PAD_LEFT

        # KPI name
        c.setFillColor(self._INK)
        c.setFont('IBMPlexSans-Bold', 9.5)
        c.drawString(text_x, h - self.PAD_TOP - 8, kpi)

        # Severity tag (top right)
        tag_x = w - self.TAG_W - self.PAD_RIGHT
        tag_y = h - self.PAD_TOP - 11
        c.setFillColor(priority_color)
        c.roundRect(tag_x, tag_y, self.TAG_W, self.TAG_H, 6.5, fill=1, stroke=0)
        c.setFillColor(self._WHITE)
        c.setFont('IBMPlexSans-Bold', 6.5)
        c.drawCentredString(tag_x + self.TAG_W / 2, tag_y + 3, priority.upper())

        # Number — mono bold
        c.setFillColor(self._INK)
        c.setFont('IBMPlexMono-Bold', 13)
        c.drawString(text_x, h - self.PAD_TOP - 24, number)

        # Reason — wrapped, muted
        c.setFillColor(self._GRAY)
        c.setFont(self.TEXT_FONT, self.TEXT_SIZE)
        reason_y = h - self.PAD_TOP - 39
        for i, line in enumerate(self._reason_lines):
            c.drawString(text_x, reason_y - i * self.LINE_H, line)

        # Action — arrowed, mint, wrapped
        c.setFillColor(self._MINT)
        c.setFont(self.TEXT_FONT, self.TEXT_SIZE)
        action_y = reason_y - len(self._reason_lines) * self.LINE_H
        for i, line in enumerate(self._action_lines):
            c.drawString(text_x, action_y - i * self.LINE_H, line)

        c.restoreState()


