def _is_percentage_col(col_name: str, series: pd.Series) -> bool:
    name = col_name.lower()
    if '%' in name or 'percent' in name or name.startswith('pct') or name.endswith('pct'):
        return True
    if 'rate' in name or 'ratio' in name:
        clean = _try_clean_numeric_series(series).dropna()
        if len(clean) == 0:
            return False
        if float(clean.max()) > 5:
            return False
        return True
    return False


def _is_currency_col(col_name: str, series: pd.Series) -> bool:
    name = col_name.lower()
    currency_keywords = ['amount', 'price', 'cost', 'fee', 'billable', 'revenue', 'salary', 'wage', 'budget', 'pay', 'hourly', 'rate']
    if any(kw in name for kw in currency_keywords):
        clean = _try_clean_numeric_series(series).dropna()
        if len(clean) > 0 and float(clean.max()) > 5:
            return True
    return False


def _is_per_unit_col(col_name: str) -> bool:
    name = col_name.lower()
    per_unit_keywords = ['rate', 'price', 'wage', 'hourly', 'per']
    return any(kw in name for kw in per_unit_keywords)


def _build_data_table(df: pd.DataFrame, brand_color: str, content_width: float) -> Table:
    def _hex_to_color(hex_str):
        hex_str = hex_str.lstrip('#')
        r, g, b = tuple(int(hex_str[i:i+2], 16) / 255.0 for i in (0, 2, 4))
        return colors.Color(r, g, b)

    even_row = _hex_to_color('#F2F1EB')
    odd_row = _hex_to_color(PAPER_BG)
    border = _hex_to_color(RULE)
    ink = _hex_to_color(INK)

    numeric_cols = set(
        c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])
    )
    date_cols = set(
        c for c in df.columns if pd.api.types.is_datetime64_any_dtype(df[c])
    )

    MAX_CELL_CHARS = 18
    def _fmt(val, col):
        if pd.isna(val):
            return ''
        if col in numeric_cols:
            if isinstance(val, float):
                return f'{val:,.2f}' if val != int(val) else f'{int(val):,}'
            return f'{val:,}'
        text = str(val)
        return _truncate_words(text, MAX_CELL_CHARS)

    headers = [str(col).upper() for col in df.columns]
    rows = [[_fmt(row[col], col) for col in df.columns]
            for _, row in df.iterrows()]
    data = [headers] + rows

    # Size each column from the *actual rendered* cell text (exact font metrics)
    # rather than raw `astype(str)` samples: datetime64 → str drops the time
    # component and numeric str() lacks the thousands separators `_fmt` adds,
    # both of which used to under-size columns and make text spill sideways.
    MIN_W, MAX_W = 40, 130
    PAD = 6  # matches LEFTPADDING / RIGHTPADDING below
    HEADER_FONT, HEADER_SIZE = 'IBMPlexSans-Bold', 8
    CELL_FONT, CELL_SIZE = 'IBMPlexMono', 7.5
    col_widths = []
    for col in df.columns:
        samples = [_fmt(v, col) for v in df[col].dropna().head(20)]
        data_w = max(
            (pdfmetrics.stringWidth(s, CELL_FONT, CELL_SIZE) for s in samples),
            default=0.0,
        )
        hdr_w = pdfmetrics.stringWidth(str(col).upper(), HEADER_FONT, HEADER_SIZE)
        w = min(MAX_W, max(MIN_W, max(hdr_w, data_w) + 2 * PAD + 6))
        col_widths.append(w)

    total = sum(col_widths)
    if total > content_width:
        scale = content_width / total
        col_widths = [w * scale for w in col_widths]

    table = Table(data, colWidths=col_widths, repeatRows=1)

    muted = _hex_to_color(MUTED)
    rule_strong = _hex_to_color(RULE_STRONG)

    style_cmds = [
        # Plain uppercase mono column labels on PAPER — no colored band.
        ('FONTNAME', (0, 0), (-1, 0), 'IBMPlexMono'),
        ('FONTSIZE', (0, 0), (-1, 0), 8),
        ('TEXTCOLOR', (0, 0), (-1, 0), muted),
        ('FONTNAME', (0, 1), (-1, -1), 'IBMPlexMono'),
        ('FONTSIZE', (0, 1), (-1, -1), 7.5),
        ('TEXTCOLOR', (0, 1), (-1, -1), ink),
        ('ROWHEIGHT', (0, 0), (-1, -1), 18),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), PAD),
        ('RIGHTPADDING', (0, 0), (-1, -1), PAD),
        # Hairline rule beneath the header row, matching the section-header language.
        ('LINEBELOW', (0, 0), (-1, 0), 0.75, rule_strong),
        ('LINEBELOW', (0, 1), (-1, -1), 0.5, border),
        ('GRID', (0, 0), (-1, -1), 0, white),
    ]

    for i in range(1, len(data)):
        bg = even_row if i % 2 == 0 else odd_row
        style_cmds.append(('BACKGROUND', (0, i), (-1, i), bg))

    for j, col in enumerate(df.columns):
        if col in numeric_cols:
            style_cmds.append(('ALIGN', (j, 1), (j, -1), 'RIGHT'))
        elif col in date_cols:
            style_cmds.append(('ALIGN', (j, 1), (j, -1), 'CENTER'))
        else:
            style_cmds.append(('ALIGN', (j, 1), (j, -1), 'LEFT'))
        style_cmds.append(('ALIGN', (j, 0), (j, 0), 'CENTER'))

    table.setStyle(TableStyle(style_cmds))
    return table


def _compute_kpi_data(df: pd.DataFrame, config: dict, ai_content: dict, brand_color_hex: str) -> list[dict]:
    if config.get("_precomputed_kpis"):
        return config["_precomputed_kpis"]

    metric_cols = config.get('metric_columns', [])
    if not metric_cols:
        metric_cols = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])]
    metric_cols = metric_cols[:5]

    from app.services.data_service import _compute_trend, _compute_trend_percentage, _try_clean_numeric

    kpis = []
    for col in metric_cols:
        if col not in df.columns:
            continue
        series = _try_clean_numeric(df[col]).dropna()
        if len(series) == 0:
            continue
        is_pct = _is_percentage_col(col, df[col])
        is_currency = not is_pct and _is_currency_col(col, df[col])
        is_per_unit = is_currency and _is_per_unit_col(col)
        if is_pct or is_per_unit:
            kpi_value = series.mean()
            prefix = 'Avg'
        else:
            kpi_value = series.sum()
            prefix = 'Total'
        trend = _compute_trend(series)
        trend_pct = _compute_trend_percentage(series, df, config.get("date_column"))
        has_date_col = bool(config.get("date_column"))
        trend_label = 'recent' if has_date_col else 'change'
        kpis.append({
            'name': f'{prefix} ' + col.replace('_', ' ').title(),
            'value': _fmt_kpi_value(kpi_value, is_currency) + ('%' if is_pct else ''),
            'trend': trend,
            'trend_pct': trend_pct,
            'trend_label': trend_label,
        })
    return kpis[:5]


