    if 'insights' in config.get('sections', []):
        section_order.append('insights')
        body_story.append(_TOCPageMarker('insights', toc_page_map))
        body_story.append(_SectionHeader('AI Insights', brand_color, content_width))
        body_story.append(Spacer(1, 6))
        if ai_skipped:
            body_story.append(_AISkippedCard(width=content_width))
            body_story.append(Spacer(1, 10))
        elif insights:
            for i, ins in enumerate(insights[:5], start=1):
                card = _InsightCard(ins, index=i, width=content_width)
                body_story.append(card)
                body_story.append(Spacer(1, 8))
        body_story.append(PageBreak())

    # ────────────────────────────────────────────────────────────
    # SECTION 6 — Anomaly Flags
    # ────────────────────────────────────────────────────────────
    anomalies = ai_content.get('anomalies') or []
    if 'anomalies' in config.get('sections', []) and anomalies:
        section_order.append('anomalies')
        body_story.append(_TOCPageMarker('anomalies', toc_page_map))
        body_story.append(_SectionHeader('Anomaly Flags', brand_color, content_width))
        body_story.append(Spacer(1, 10))
        for anomaly in anomalies[:10]:
            box = _AnomalyBox(anomaly, width=content_width)
            body_story.append(box)
            body_story.append(Spacer(1, 6))
        body_story.append(PageBreak())

    # ────────────────────────────────────────────────────────────
    # SECTION 7 — Data Table
    # ────────────────────────────────────────────────────────────
    if 'data_table' in config.get('sections', []):
        section_order.append('data_table')
        body_story.append(_TOCPageMarker('data_table', toc_page_map))
        body_story.append(_SectionHeader('Data Table', brand_color, content_width))
        body_story.append(Spacer(1, 10))
        # Provenance caption — honest row count from original df, date range from actual data, exclusion claim only if verifiable
        n_records = len(df)
        date_col = config.get('date_column')
        date_range_text = ''
        if date_col and date_col in df.columns:
            try:
                _dates = pd.to_datetime(df[date_col], errors='coerce').dropna()
                if len(_dates) >= 1:
                    _min = _dates.min()
                    _max = _dates.max()
                    date_range_text = f"{_min.strftime('%b %d, %Y')} \u2013 {_max.strftime('%b %d, %Y')}"
            except Exception:
                date_range_text = ''
        raw_nulls = config.get('_raw_null_counts') or {}
        is_clean = not any(v and int(v) > 0 for v in raw_nulls.values()) if isinstance(raw_nulls, dict) else True
        # Only claim "No records excluded" when we can verify no nulls/invalid rows and not truncated for display
        if date_range_text:
            if is_clean:
                _prov_text = f"Based on {n_records} records \u2022 {date_range_text} \u2022 No records excluded."
            else:
                _prov_text = f"Based on {n_records} records \u2022 {date_range_text}"
        else:
            if is_clean:
                _prov_text = f"Based on {n_records} records \u2022 No records excluded."
            else:
                _prov_text = f"Based on {n_records} records"
        _prov_style = ParagraphStyle('ProvenanceCaption', fontName='IBMPlexSans', fontSize=8, textColor=HexColor(MUTED), alignment=TA_CENTER, leading=11, spaceAfter=6)
        body_story.append(Paragraph(_prov_text, _prov_style))
        body_story.append(Spacer(1, 4))

        display_df = df.copy()
        if len(display_df) > 50:
            display_df = display_df.head(50)
        # Column cap: beyond 8 cols the table becomes illegible (see wide-table visual audit)
        MAX_DISPLAY_COLS = 8
        cols_truncated = None
        if len(display_df.columns) > MAX_DISPLAY_COLS:
            cols_truncated = len(display_df.columns)
            display_df = display_df.iloc[:, :MAX_DISPLAY_COLS]

        data_table = _build_data_table(display_df, brand_color, content_width)
        body_story.append(data_table)
        if cols_truncated is not None:
            note_style = ParagraphStyle('ColCapNote', fontName='IBMPlexSans', fontSize=7, textColor=HexColor(MUTED), alignment=TA_CENTER, leading=10, spaceBefore=6)
            body_story.append(Paragraph(f"Showing first {MAX_DISPLAY_COLS} of {cols_truncated} columns \u2014 see Excel export for full data.", note_style))
        body_story.append(PageBreak())

    # ────────────────────────────────────────────────────────────
    # SECTION 8 — Recommendations
    # ────────────────────────────────────────────────────────────
    show_recommendations = (
        'insights' in config.get('sections', [])
        or 'executive_summary' in config.get('sections', [])
    ) and not ai_skipped
    if show_recommendations:
        section_order.append('recommendations')
        body_story.append(_TOCPageMarker('recommendations', toc_page_map))
        body_story.append(_SectionHeader('Recommendations', brand_color, content_width))
        body_story.append(Spacer(1, 10))

        if ai_skipped:
            body_story.append(_AISkippedCard(width=content_width))
            body_story.append(Spacer(1, 10))
        else:
            recommendations = ai_content.get('recommendations') or []

            if recommendations:
                for idx, rec in enumerate(recommendations, 1):
                    body_story.append(_RecommendationCard(idx, rec, brand_color, content_width))
                    body_story.append(Spacer(1, 8))
            else:
                body_story.append(Paragraph('No recommendations available.', body_style))
            # Contact line — gated by prepared_by, no fallback, single appearance at end of Recommendations
            _prepared_by = (config.get('brand') or {}).get('prepared_by', '')
            if _prepared_by:
                _contact_style = ParagraphStyle('ContactLine', fontName='IBMPlexSans', fontSize=9, textColor=HexColor(MUTED), alignment=TA_CENTER, leading=12, spaceBefore=12)
                body_story.append(Paragraph(f'Questions about this report? Contact {_prepared_by}.', _contact_style))
        body_story.append(PageBreak())

    # ────────────────────────────────────────────────────────────
    # SECTION 9 — Appendix
    # ────────────────────────────────────────────────────────────
    if 'appendix' in config.get('sections', []):
        section_order.append('appendix')
        body_story.append(_TOCPageMarker('appendix', toc_page_map))
        body_story.append(_SectionHeader('Appendix — Raw Data', brand_color, content_width))
        body_story.append(Spacer(1, 10))

        appendix_df = df.copy()
        if len(appendix_df) > 100:
            appendix_df = appendix_df.head(100)
        MAX_APP_COLS = 8
        app_cols_truncated = None
        if len(appendix_df.columns) > MAX_APP_COLS:
            app_cols_truncated = len(appendix_df.columns)
            appendix_df = appendix_df.iloc[:, :MAX_APP_COLS]

        app_table_data = []
        app_header = [str(c).upper() for c in appendix_df.columns]
        app_table_data.append(app_header)
        for _, row in appendix_df.iterrows():
            app_table_data.append([str(v) if pd.notna(v) else '' for v in row])

        app_col_count = len(app_header)
        app_col_width = min(content_width / max(app_col_count, 1), 120)
        app_col_widths = [app_col_width] * app_col_count

        app_table = Table(app_table_data, colWidths=app_col_widths, repeatRows=1)

        app_style_commands = [
            # Plain uppercase mono column labels on PAPER — no colored band.
            ('FONTNAME', (0, 0), (-1, 0), 'IBMPlexMono'),
            ('FONTSIZE', (0, 0), (-1, 0), 8),
            ('TEXTCOLOR', (0, 0), (-1, 0), HexColor(MUTED)),
            ('FONTNAME', (0, 1), (-1, -1), 'IBMPlexMono'),
            ('FONTSIZE', (0, 1), (-1, -1), 7),
            ('GRID', (0, 0), (-1, -1), 0.5, HexColor(GRID_LINE)),
            # Hairline rule beneath the header row, matching the section-header language.
            ('LINEBELOW', (0, 0), (-1, 0), 0.75, HexColor(RULE_STRONG)),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('LEFTPADDING', (0, 0), (-1, -1), 4),
            ('RIGHTPADDING', (0, 0), (-1, -1), 4),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ]
        for row_idx in range(1, len(app_table_data)):
            if row_idx % 2 == 0:
                app_style_commands.append(
                    ('BACKGROUND', (0, row_idx), (-1, row_idx), HexColor(ROW_ALT_COLOR))
                )

        app_table.setStyle(TableStyle(app_style_commands))
        body_story.append(app_table)
        if app_cols_truncated is not None:
            note_style2 = ParagraphStyle('AppColCapNote', fontName='IBMPlexSans', fontSize=7, textColor=HexColor(MUTED), alignment=TA_CENTER, leading=10, spaceBefore=6)
            body_story.append(Paragraph(f"Showing first {MAX_APP_COLS} of {app_cols_truncated} columns \u2014 see Excel export for full data.", note_style2))

    # ────────────────────────────────────────────────────────────
    # TOC — two-pass build: first pass collects actual page numbers via
    # _TOCPageMarker, second pass renders TOC with correct numbers.
    # Preserves all existing TOC styling; logo download and font stripping
    # intentionally only run once (final pass) per Phase 1 cost assessment.
    # ────────────────────────────────────────────────────────────
    cover_story = list(story)  # shallow copy of cover flowables built so far

    def _build_toc_block(entries: list[tuple[str, str]]) -> list:
        rows = []
        for label, pg in entries:
            rows.append([
                _TocDot(brand_color, size=6),
                Paragraph(label, ParagraphStyle(
                    'TOCLabel',
                    fontName='IBMPlexSans',
                    fontSize=10,
                    textColor=HexColor(INK),
                    leading=16,
                )),
                Paragraph(pg, ParagraphStyle(
                    'TOCPage',
                    fontName='IBMPlexMono',
                    fontSize=9,
                    textColor=HexColor(brand_color),
                    alignment=TA_RIGHT,
                    leading=16,
                )),
            ])
        col_w2 = content_width
        table = Table(rows, colWidths=[12, col_w2 * 0.85 - 12, col_w2 * 0.15])
        table.setStyle(TableStyle([
            ('VALIGN',       (0, 0), (-1, -1), 'MIDDLE'),
            ('LEFTPADDING',  (0, 0), (-1, -1), 0),
            ('RIGHTPADDING', (0, 0), (-1, -1), 0),
            ('TOPPADDING',   (0, 0), (-1, -1), 5),
            ('BOTTOMPADDING',(0, 0), (-1, -1), 5),
            ('LINEBELOW', (0, 0), (-1, -2), 0.4, HexColor(GRID_LINE)),
        ]))
        return [_SectionHeader('Table of Contents', brand_color, content_width), Spacer(1, 12), table, PageBreak()]

    # First pass: dummy TOC (same row count, '00' keeps pagination identical) to populate toc_page_map
    dummy_entries = [('Cover Page', '01'), ('Table of Contents', '02')] + [(_TOC_LABELS[k], '00') for k in section_order]
    toc_dummy_block = _build_toc_block(dummy_entries)
    import io as _io
    _temp_buf = _io.BytesIO()
    doc_temp = SimpleDocTemplate(_temp_buf, pagesize=A4, leftMargin=MARGIN, rightMargin=MARGIN, topMargin=MARGIN, bottomMargin=MARGIN)
    story_temp = cover_story + toc_dummy_block + body_story
    try:
        doc_temp.build(story_temp, onFirstPage=on_first_page, onLaterPages=on_page)
    except Exception as e:
        logging.warning(f"[pdf_service] first pass TOC collection failed: {e}")

    # Build correct TOC from collected map (markers are zero-height, so pagination is stable)
    toc_entries: list[tuple[str, str]] = [('Cover Page', '01'), ('Table of Contents', '02')]
    for key in section_order:
        pg = toc_page_map.get(key)
        if pg is None:
            pg = 3 + section_order.index(key)
            logging.warning(f"[pdf_service] TOC marker missing for {key}, fallback to {pg}")
        toc_entries.append((_TOC_LABELS[key], str(pg).zfill(2)))

    toc_final_block = _build_toc_block(toc_entries)
    story_final = cover_story + toc_final_block + body_story

    # Final pass: reuse doc variable pointing at real pdf_path (logo_path already cached, not re-downloaded)
    doc = SimpleDocTemplate(pdf_path, pagesize=A4, leftMargin=MARGIN, rightMargin=MARGIN, topMargin=MARGIN, bottomMargin=MARGIN)
    doc.build(story_final, onFirstPage=on_first_page, onLaterPages=on_page)
    logging.info(f"[pdf_service] build_sync completed (two-pass TOC) — report_id={report_id} pages_collected={toc_page_map}")

    _strip_standard_fonts(pdf_path)

    if logo_path:
        try:
            os.unlink(logo_path)
        except OSError:
            pass

    return pdf_path
