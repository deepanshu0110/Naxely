class _SectionHeader(Flowable):
    def __init__(self, text, brand_color_hex, width=None):
        Flowable.__init__(self)
        self.text = text
        self.brand_color = HexColor(brand_color_hex)
        self._width = width or (PAGE_WIDTH - 2 * MARGIN)
        self.height = 40

    def wrap(self, availWidth, availHeight):
        return (self._width, self.height)

    def draw(self):
        # Ledger section header: plain serif heading + hairline rule, no colored band.
        self.canv.setFillColor(HexColor(INK))
        self.canv.setFont('Fraunces-SemiBold', 20)
        self.canv.drawString(0, 22, self.text)
        self.canv.setStrokeColor(HexColor(RULE_STRONG))
        self.canv.setLineWidth(0.75)
        self.canv.line(0, 8, self._width, 8)


class _KPIRow(Flowable):
    """Ledger line-item for a single KPI: serif index, metric name, mono value,
    colored trend — hairline rules above and below the row."""

    def __init__(self, kpi, index, content_width, brand_color_hex):
        Flowable.__init__(self)
        self.kpi = kpi
        self.index = index
        self.brand_color_hex = brand_color_hex
        self._width = content_width
        self.height = 48

    def wrap(self, availWidth, availHeight):
        return (self._width, self.height)

    def draw(self):
        c = self.canv
        w = self._width
        h = self.height
        c.saveState()

        # hairlines above and below the ledger row
        c.setStrokeColor(HexColor(RULE))
        c.setLineWidth(0.4)
        c.line(0, 0, w, 0)
        c.line(0, h, w, h)

        # index — serif, muted
        c.setFillColor(HexColor(MUTED))
        c.setFont('Fraunces-Medium', 13)
        c.drawString(0, h - 30, str(self.index).zfill(2))

        # name — bold sans
        c.setFillColor(HexColor(INK))
        c.setFont('IBMPlexSans-Bold', 10)
        c.drawString(30, h - 18, str(self.kpi.get('name', '')))

        # value — mono bold, right of centre
        value = str(self.kpi.get('value', ''))
        c.setFillColor(HexColor(INK))
        c.setFont('IBMPlexMono-Bold', 14)
        c.drawRightString(w - 88, (h - 14) / 2 - 2, value)

        # trend — colored, far right. Colorblind-safe: arrow shape + sign +
        # color all carry direction, and up/down use the semantic ledger
        # mint/rust pair consistently with the AI insight cards.
        trend_pct = self.kpi.get('trend_pct', 0) or 0
        trend_color = DELTA_UP if trend_pct >= 0 else RUST
        sign = '+' if trend_pct >= 0 else '-'
        arrow = '\u2191' if trend_pct >= 0 else '\u2193'
        c.setFillColor(HexColor(trend_color))
        c.setFont('IBMPlexSans-Bold', 9)
        c.drawRightString(w, (h - 9) / 2 - 2,
                          f"{arrow} {sign} {abs(trend_pct):.1f}%")

        # qualifier under the trend — labels which calculation produced the
        # % (monthly-aggregate trend vs raw first-to-last), so the card never
        # silently contradicts a chart caption that uses the other measure
        qualifier = _trend_qualifier(self.kpi.get('trend_label', ''))
        if qualifier:
            c.setFillColor(HexColor(MUTED))
            c.setFont('IBMPlexSans-Bold', 6.5)
            c.drawRightString(w, 3, qualifier)

        c.restoreState()


class _KPICard(Flowable):
    """Tinted card for a single KPI — vertical layout, larger value."""

    def __init__(self, kpi, index, width, brand_color_hex):
        Flowable.__init__(self)
        self.kpi = kpi
        self.index = index
        self.width = width
        self.brand_color_hex = brand_color_hex
        self.height = 110

    def wrap(self, availWidth, availHeight):
        return (self.width, self.height)

    def draw(self):
        kpi = self.kpi
        w = self.width
        h = self.height
        c = self.canv
        c.saveState()
        # tinted background
        tint = _brand_tint(self.brand_color_hex, alpha=0.07)
        c.setFillColor(tint)
        c.roundRect(0, 0, w, h, 8, fill=1, stroke=0)
        # hairline border
        c.setStrokeColor(HexColor(RULE))
        c.setLineWidth(0.6)
        c.roundRect(0, 0, w, h, 8, fill=0, stroke=1)
        # index — top left, muted serif
        c.setFillColor(HexColor(MUTED))
        c.setFont('Fraunces-Medium', 10)
        c.drawString(10, h - 18, str(self.index).zfill(2))
        # name — bold sans, centered below index
        name = str(kpi.get('name', '') or '')
        c.setFillColor(HexColor(MUTED))
        c.setFont('IBMPlexSans-Bold', 7.5)
        # keep original case to match PDF text extraction (test expects 'Total Units Sold', not upper)
        avail_name_w = w - 20
        display_name = name
        if c.stringWidth(display_name, 'IBMPlexSans-Bold', 7.5) > avail_name_w:
            display_name = _truncate_words(display_name, 28)
        c.drawCentredString(w/2, h - 30, display_name)
        # value — large mono bold, centered
        value = str(kpi.get('value', '') or '')
        c.setFillColor(HexColor(INK))
        c.setFont('IBMPlexMono-Bold', 26)
        c.drawCentredString(w/2, h/2 + 2, value)
        # trend — colored, centered below value
        trend_pct = kpi.get('trend_pct', 0) or 0
        trend_color = DELTA_UP if trend_pct >= 0 else RUST
        sign = '+' if trend_pct >= 0 else ''
        arrow = '\u2191' if trend_pct >= 0 else '\u2193'
        c.setFillColor(HexColor(trend_color))
        c.setFont('IBMPlexSans-Bold', 9)
        c.drawCentredString(w/2, h/2 - 16, f"{arrow} {sign}{abs(trend_pct):.1f}%")
        qualifier = _trend_qualifier(kpi.get('trend_label', ''))
        if qualifier:
            c.setFillColor(HexColor(MUTED))
            c.setFont('IBMPlexSans-Bold', 6.5)
            c.drawCentredString(w/2, h/2 - 28, qualifier)
        c.restoreState()


def _build_kpi_grid_flowables(kpis: list[dict], brand_color: str, content_width: float) -> list:
    """Shared KPI grid builder — single source for merged and standalone KPI pages.

    Branches: n<=3 single row (n==1 centered at 60% width), n==4 2x2, n==5 3+2 (BOTTOM2 sentinel).
    Fixes n==1 clipping: card width must equal table cell width (single_w), not content_width.
    Returns list of Flowables (Tables + Spacers) ready to append to story.
    """
    n = len(kpis)
    if n == 0:
        return []
    gap = 12
    cards = [(kpi, i) for i, kpi in enumerate(kpis, start=1)]
    rows: list = []
    if n == 1:
        single_w = min(content_width * 0.60, 300)
        rows.append([_KPICard(cards[0][0], cards[0][1], single_w, brand_color)])
    elif n <= 3:
        card_w = (content_width - gap * (n - 1)) / n
        row = [_KPICard(kpi, idx, card_w, brand_color) for kpi, idx in cards]
        rows.append(row)
    elif n == 4:
        card_w = (content_width - gap) / 2
        rows.append([_KPICard(cards[0][0], cards[0][1], card_w, brand_color), _KPICard(cards[1][0], cards[1][1], card_w, brand_color)])
        rows.append([_KPICard(cards[2][0], cards[2][1], card_w, brand_color), _KPICard(cards[3][0], cards[3][1], card_w, brand_color)])
    else:  # n == 5
        card_w3 = (content_width - gap * 2) / 3
        rows.append([_KPICard(cards[0][0], cards[0][1], card_w3, brand_color), _KPICard(cards[1][0], cards[1][1], card_w3, brand_color), _KPICard(cards[2][0], cards[2][1], card_w3, brand_color)])
        rows.append('BOTTOM2')
    # Build flowables
    flowables: list = []
    # Need bottom_cards for n==5 case
    bottom_cards = [cards[3], cards[4]] if n == 5 else []
    for idx, row in enumerate(rows):
        if row == 'BOTTOM2':
            card_w2 = (content_width - gap) / 2
            t = Table([[_KPICard(bottom_cards[0][0], bottom_cards[0][1], card_w2, brand_color), _KPICard(bottom_cards[1][0], bottom_cards[1][1], card_w2, brand_color)]], colWidths=[card_w2, card_w2], hAlign='CENTER', spaceBefore=6, spaceAfter=6)
            t.setStyle(TableStyle([
                ('LEFTPADDING', (0, 0), (-1, -1), 6),
                ('RIGHTPADDING', (0, 0), (-1, -1), 6),
                ('TOPPADDING', (0, 0), (-1, -1), 0),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
                ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ]))
            flowables.append(t)
        else:
            cols = len(row)  # type: ignore
            if cols == 1:
                single_w = min(content_width * 0.60, 300)
                t = Table([[row[0]]], colWidths=[single_w], hAlign='CENTER')  # type: ignore
            elif cols == 2:
                card_w = (content_width - gap) / 2
                t = Table([row], colWidths=[card_w] * 2, hAlign='CENTER')  # type: ignore
            elif cols == 3:
                card_w = (content_width - gap * 2) / 3
                t = Table([row], colWidths=[card_w] * 3, hAlign='CENTER')  # type: ignore
            else:
                t = Table([row], hAlign='CENTER')  # type: ignore
            t.setStyle(TableStyle([
                ('LEFTPADDING', (0, 0), (-1, -1), 6),
                ('RIGHTPADDING', (0, 0), (-1, -1), 6),
                ('TOPPADDING', (0, 0), (-1, -1), 6),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
                ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ]))
            flowables.append(t)
        if idx < len(rows) - 1:
            flowables.append(Spacer(1, gap))
    return flowables


class _TOCPageMarker(Flowable):
    """Zero-height marker that records its actual page number during layout.

    Inserted immediately before each section's _SectionHeader. During the
    first layout pass, draw() captures self.canv.getPageNumber() into the
    shared page_map dict. The second pass then builds the TOC with those
    accurate numbers, preserving all existing TOC styling.
    """
    def __init__(self, key: str, page_map: dict):
        Flowable.__init__(self)
        self.key = key
        self.page_map = page_map
        self.width = 0
        self.height = 0

    def wrap(self, availWidth, availHeight):
        return (0, 0)

    def draw(self):
        try:
            self.page_map[self.key] = int(self.canv.getPageNumber())
        except Exception:
            pass


def _wrap_text_lines(text: str, font_name: str, font_size: float, max_width: float) -> list[str]:
    """Greedy word wrap of `text` to `max_width` at the given font. Returns a
    list of lines, each fitting the box; an unbreakable word wider than the box
    is emitted alone rather than dropped."""
    lines, cur = [], ''
    for word in text.split(' '):
        trial = f'{cur} {word}'.strip()
        if cur and pdfmetrics.stringWidth(trial, font_name, font_size) > max_width:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines


def _fit_text_lines(text: str, font_name: str, font_size: float, max_width: float, max_lines: int) -> list[str]:
    """Wrap `text` to at most `max_lines` lines that fit `max_width`. When the
    text is longer, the final line is truncated at a word boundary with '…'
    rather than cutting mid-word."""
    lines = _wrap_text_lines(text, font_name, font_size, max_width)
    if len(lines) <= max_lines:
        return lines
    head = lines[:max_lines - 1]
    words = ' '.join(lines[max_lines - 1:]).split(' ')
    for n in range(len(words), 0, -1):
        candidate = ' '.join(words[:n]) + '\u2026'
        if pdfmetrics.stringWidth(candidate, font_name, font_size) <= max_width:
            return head + [candidate]
    return head + ['\u2026']


def _trend_qualifier(label: str) -> str:
    """Human-readable qualifier for a KPI trend %. Maps the machine
    `trend_label` ('recent' = monthly-aggregate trend, 'change' = raw
    first-to-last) to the phrase printed under the Key Metrics %."""
    return {
        'recent': 'monthly trend',
        'change': 'first-to-last',
    }.get(label, label)


def _truncate_words(text: str, limit: int) -> str:
    """Truncate `text` to at most `limit` characters at a word boundary,
    appending '…' — the char-based analogue of `_fit_text_lines` used where a
    fixed budget (table cells) applies. A single unbreakable word wider than
    the budget is cut at the limit rather than dropped."""
    if len(text) <= limit:
        return text
    words = text.split(' ')
    for n in range(len(words), 0, -1):
        candidate = ' '.join(words[:n])
        if len(candidate) <= limit - 1:
            return candidate + '\u2026'
    return text[:limit - 1] + '\u2026'


def _sanitize_for_pdf(text: str) -> str:
    """Replace Unicode chars not covered by IBMPlexSans/Fraunces.

    The Groq AI model frequently emits U+2011 (non-breaking hyphen) in
    strings like '6.54-hour', which renders as a box glyph in the PDF
    because the TTF lacks that codepoint. Replace with the nearest
    ASCII equivalent generically, since summary text varies per report.
    """
    if not text:
        return text
    repl = {
        '\u2011': '-',  # non-breaking hyphen — the observed box-glyph culprit
        '\u2010': '-',
        '\u2012': '-',
        '\u2013': '-',  # en dash
        '\u2014': '-',  # em dash
        '\u00a0': ' ',  # NBSP
        '\u2009': ' ',  # thin space
        '\u202f': ' ',  # narrow NBSP
        '\u2000': ' ',
        '\u2001': ' ',
        '\u2002': ' ',
        '\u2003': ' ',
        '\u2004': ' ',
        '\u2005': ' ',
        '\u2006': ' ',
        '\u2007': ' ',
        '\u2008': ' ',
        '\u200a': ' ',
        '\u205f': ' ',
        '\u2018': "'",  # left single quote
        '\u2019': "'",  # right single quote
        '\u201c': '"',  # left double quote
        '\u201d': '"',  # right double quote
    }
    for k, v in repl.items():
        text = text.replace(k, v)
    return text


class _InsightCard(Flowable):
    """Tinted card with severity accent — fixes number clipping, adds background."""

    CARD_H = 84
    LINE_H = 10
    PAD_LEFT = 30
    PAD_TOP = 12
    PAD_RIGHT = 8
    TAG_W = 44
    TAG_H = 13
    TEXT_FONT = 'IBMPlexSans'
    TEXT_SIZE = 8
    NUMBER_FONT = 'IBMPlexMono-Bold'
    NUMBER_SIZE = 13
    MAX_LINES = 2

    _MINT = HexColor(DELTA_UP)
    _RED = HexColor(RUST)
    _AMBER = HexColor('#B45309')
    _INK = HexColor(INK)
    _GRAY = HexColor(MUTED)
    _WHITE = HexColor('#FFFFFF')

    _PRIORITY_COLORS = {
        'high': _RED,
        'medium': _AMBER,
        'low': _MINT,
    }
    _PRIORITY_HEX = {
        'high': RUST,
        'medium': '#B45309',
        'low': DELTA_UP,
    }

    def __init__(self, insight, index=1, width=None):
        Flowable.__init__(self)
        self.insight = insight
        self.index = index
        self._width = width or (PAGE_WIDTH - 2 * MARGIN)
        self._reason_lines = []
        self._action_lines = []
        self._number_lines = []
        self._layout_text()

    def _layout_text(self):
        ins = self.insight
        number = _sanitize_for_pdf(str(ins.get('number', '') or ''))
        reason = _sanitize_for_pdf(str(ins.get('reason', '') or ''))
        action = _sanitize_for_pdf(str(ins.get('action', '') or ''))
        avail_w = self._width - self.PAD_LEFT - self.PAD_RIGHT
        self._number_lines = _fit_text_lines(number, self.NUMBER_FONT, self.NUMBER_SIZE, avail_w, self.MAX_LINES)
        self._reason_lines = _fit_text_lines(
            reason, self.TEXT_FONT, self.TEXT_SIZE, avail_w, self.MAX_LINES)
        self._action_lines = _fit_text_lines(
            '\u2192 ' + action, self.TEXT_FONT, self.TEXT_SIZE, avail_w, self.MAX_LINES)

    def wrap(self, availWidth, availHeight):
        extra = (len(self._number_lines) - 1) + (len(self._reason_lines) - 1) + (len(self._action_lines) - 1)
        # number lines are taller (13pt vs 8pt) so add extra for number if needed
        if len(self._number_lines) > 1:
            extra += (len(self._number_lines) - 1) * 0.4
        self.width, self.height = self._width, self.CARD_H + extra * self.LINE_H
        return (self.width, self.height)

    def draw(self):
        ins = self.insight
        kpi = _sanitize_for_pdf(str(ins.get('kpi', '') or ''))
        priority = str(ins.get('priority', 'medium')).lower()

        priority_color = self._PRIORITY_COLORS.get(priority, self._AMBER)
        priority_hex = self._PRIORITY_HEX.get(priority, '#B45309')
        w = self._width
        c = self.canv
        h = self.height
        c.saveState()
        # tinted background — alpha 0.12 matching cover hero panel for clear severity tint
        tint = _brand_tint(priority_hex, alpha=0.12)
        c.setFillColor(tint)
        c.roundRect(0, 0, w, h, 6, fill=1, stroke=0)
        # left accent strip — 5pt for clear severity cue
        c.setFillColor(priority_color)
        c.roundRect(0, 0, 5, h, 1.5, fill=1, stroke=0)
        # hairline below the ledger row
        c.setStrokeColor(HexColor(RULE))
        c.setLineWidth(0.4)
        c.line(0, 0, w, 0)

        # index — serif, muted
        c.setFillColor(self._GRAY)
        c.setFont('Fraunces-Medium', 14)
        c.drawString(8, h - 26, str(self.index).zfill(2))

        text_x = self.PAD_LEFT

        # KPI name
        c.setFillColor(self._INK)
        c.setFont('IBMPlexSans-Bold', 9.5)
        c.drawString(text_x, h - self.PAD_TOP - 8, kpi)

        # Severity tag (top right) — keep as is
        tag_x = w - self.TAG_W - self.PAD_RIGHT
        tag_y = h - self.PAD_TOP - 11
        c.setFillColor(priority_color)
        c.roundRect(tag_x, tag_y, self.TAG_W, self.TAG_H, 6.5, fill=1, stroke=0)
        c.setFillColor(self._WHITE)
        c.setFont('IBMPlexSans-Bold', 6.5)
        c.drawCentredString(tag_x + self.TAG_W / 2, tag_y + 3, priority.upper())

        # Number — wrapped, mono bold, larger
        c.setFillColor(self._INK)
        c.setFont(self.NUMBER_FONT, self.NUMBER_SIZE)
        number_y = h - self.PAD_TOP - 26
        for i, line in enumerate(self._number_lines):
            c.drawString(text_x, number_y - i * 14, line)

        # Reason — wrapped, muted
        c.setFillColor(self._GRAY)
        c.setFont(self.TEXT_FONT, self.TEXT_SIZE)
        reason_y = number_y - len(self._number_lines) * 14 - 2
        for i, line in enumerate(self._reason_lines):
            c.drawString(text_x, reason_y - i * self.LINE_H, line)

        # Action — arrowed, mint, wrapped
        c.setFillColor(self._MINT)
        c.setFont(self.TEXT_FONT, self.TEXT_SIZE)
        action_y = reason_y - len(self._reason_lines) * self.LINE_H - 2
        for i, line in enumerate(self._action_lines):
            c.drawString(text_x, action_y - i * self.LINE_H, line)

        c.restoreState()


