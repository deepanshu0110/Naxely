def _validate_url_scheme(url: str) -> None:
    parsed = urllib.parse.urlparse(url)
    if parsed.scheme not in ("http", "https"):
        raise ValueError(f"URL scheme '{parsed.scheme}' is not allowed (only http/https)")


def _download_logo(logo_url: str) -> str | None:
    t0 = time.time()
    logging.info("[pdf_service] logo download start")
    try:
        _validate_url_scheme(logo_url)
        req = urllib.request.Request(logo_url, headers={'User-Agent': 'Naxely/1.0'})
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = resp.read()
        elapsed = round(time.time() - t0, 2)
        logging.info(f"[pdf_service] logo download done: {elapsed:.2f}s")

        img = PILImage.open(io.BytesIO(data)).convert('RGBA')

        # Resize logo to max height 36px (fits cleanly in cover band)
        max_h = 36
        if img.height > max_h:
            ratio = max_h / img.height
            img = img.resize((int(img.width * ratio), max_h), PILImage.Resampling.LANCZOS)

        # Add padding around the logo
        pad_x, pad_y = 12, 8
        badge_w = img.width + pad_x * 2
        badge_h = img.height + pad_y * 2

        # Create white background with rounded corners using PIL
        from PIL import ImageDraw
        badge = PILImage.new('RGBA', (badge_w, badge_h), (0, 0, 0, 0))
        draw = ImageDraw.Draw(badge)
        draw.rounded_rectangle(
            [(0, 0), (badge_w - 1, badge_h - 1)],
            radius=6,
            fill=(255, 255, 255, 255)
        )
        # Paste logo centered on badge
        badge.paste(img, (pad_x, pad_y), mask=img.split()[3])

        # Save as RGBA PNG with transparent corners (badge on transparent canvas)
        tmp = tempfile.NamedTemporaryFile(suffix='.png', delete=False)
        tmp_path = tmp.name
        tmp.close()
        badge.save(tmp_path, 'PNG')

        logging.info(f"[pdf_service] _download_logo success: {tmp_path}")
        return tmp_path
    except Exception as e:
        logging.warning(f"[pdf_service] _download_logo failed: {e}")
        return None


def _fmt_kpi_value(val: float, is_currency: bool = False) -> str:
    prefix = '$' if is_currency else ''
    if abs(val) >= 1_000_000:
        return f'{prefix}{val/1_000_000:.1f}M'
    if abs(val) >= 1_000:
        return f'{prefix}{val/1_000:.1f}K'
    if isinstance(val, float) and val != int(val):
        return f'{prefix}{val:.2f}'
    return f'{prefix}{int(val):,}'


